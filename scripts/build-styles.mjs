import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

// Keep every original rule and its cascade order. No minification or deferred CSS.
export function buildStyles(root, { check = false } = {}) {
  const manifest = resolve(root, 'scripts/stylesheets.json');
  if (!existsSync(manifest)) return [];
  const sources = JSON.parse(readFileSync(manifest, 'utf8'));
  const content = '/* Generated by scripts/version-assets.mjs; edit the original stylesheets. */\n'
    + sources.map(name => `/* Source: ${name} */\n${readFileSync(resolve(root, name), 'utf8')}\n`).join('\n');
  const target = resolve(root, 'site-bundle.css');
  if (existsSync(target) && readFileSync(target, 'utf8') === content) return [];
  if (!check) writeFileSync(target, content);
  return ['site-bundle.css'];
}
