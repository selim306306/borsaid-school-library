import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildStyles } from '../scripts/build-styles.mjs';
const root = new URL('../', import.meta.url).pathname;
const read = name => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
const sources = JSON.parse(read('scripts/stylesheets.json'));
test('all 27 stylesheets retain exact bytes and intended cascade order', () => {
  assert.equal(sources.length, 27);
  assert.equal(new Set(sources).size, 27);
  assert.equal(sources[0], 'site.css');
  assert.ok(sources.includes('staff-library-experiment.css'));
  assert.equal(sources.at(-2), 'mobile-touch-targets.css');
  assert.equal(sources.at(-1), 'reader-theme.css');
  const expected = '/* Generated by scripts/version-assets.mjs; edit the original stylesheets. */\n'
    + sources.map(name => `/* Source: ${name} */\n${read(name)}\n`).join('\n');
  assert.equal(read('site-bundle.css'), expected);
  assert.deepEqual(buildStyles(root, { check: true }), []);
});
test('homepage uses one local blocking CSS request without deferral or missing features', () => {
  const html = read('index.html');
  const local = [...html.matchAll(/<link rel="stylesheet" href="([^\"]+)"/g)].map(m => m[1]);
  assert.equal(local.length, 1);
  assert.match(local[0], /^site-bundle\.css\?v=[a-f0-9]{16}$/);
  assert.doesNotMatch(html, /media="print"|onload="this\.media/);
  for (const name of sources) assert.doesNotMatch(read(name), /@charset|@import/);
});
